def test_finding_block_is_refused(tmp_path, caplog, tag_body):
    gerrit = RetriggerGerrit(messages=[_bot_message(tag_body)])
    store = DedupStore(str(tmp_path / "voted.db"))
    store.record_attempt("rebar~main~Iabc", "rev2")

