# ── worker routing + /rerun budget re-arm (AC4) ─────────────────────────────────


def test_worker_routes_comment_added_and_requeues_forced_event(monkeypatch, tmp_path):
    """A comment-added event is routed to retrigger (never to review_and_vote), and an
    accepted trigger's forced event is REQUEUED and then reviewed on its next dequeue."""
    pytest.importorskip("fastapi")
    import asyncio
    import contextlib

    from rebar.review_bot import app as appmod

    forced_event = {
        "type": "manual-rerun",
        "change": {"id": "rebar~main~Iabc", "number": 42, "project": "rebar"},
        "patchSet": {"number": 2, "revision": "rev2", "ref": "refs/changes/42/42/2"},
        "_rebar_force": True,
    }
    handled: list[dict] = []

    def fake_handle(event, *, config=None, gerrit=None, dedup=None):
        handled.append(event)
        return dict(forced_event)

    monkeypatch.setattr(retrigger, "handle_comment_added", fake_handle)

    reviewed: list[tuple[str, bool]] = []

    async def fake_review_and_vote(event, *, config, force=False):
        reviewed.append((event["change"]["id"], force))
        return {"status": "voted"}

    monkeypatch.setattr(appmod._voter, "review_and_vote", fake_review_and_vote)

    async def drive():
        queue: asyncio.Queue = asyncio.Queue()
        queue.put_nowait(_comment_event())
        worker = asyncio.create_task(appmod._worker(queue, _cfg(tmp_path)))
        try:
            await queue.join()
        finally:
            worker.cancel()
            with contextlib.suppress(asyncio.CancelledError):
                await worker

    asyncio.run(asyncio.wait_for(drive(), timeout=10))

    assert len(handled) == 1 and handled[0]["type"] == "comment-added"
    # the comment event itself was NOT reviewed; the requeued forced event WAS, force=True
    assert reviewed == [("rebar~main~Iabc", True)]


def test_rerun_resets_attempts_budget(monkeypatch, tmp_path):
    """AC4: the operator /rerun re-arms the 0347 attempts budget before enqueueing —
    a force on a stale exhausted budget must not immediately re-escalate."""
    pytest.importorskip("fastapi")
    import asyncio

    from starlette.testclient import TestClient

    from rebar.review_bot import app as appmod
    from rebar.review_bot import gerrit_client as gcmod

    cfg = _cfg(tmp_path)
    monkeypatch.setattr(appmod.app.state, "config", cfg, raising=False)

    async def _idle_worker(queue, cfg):
        await asyncio.Event().wait()

    async def _idle_loop(*, config):
        await asyncio.Event().wait()

    monkeypatch.setattr(appmod, "_worker", _idle_worker, raising=True)
    monkeypatch.setattr(appmod._reconcile, "reconcile_loop", _idle_loop, raising=True)
    # The idle worker never task_done()s the queued force event, so bound the
    # shutdown drain (queue.join()) or TestClient.__exit__ hangs for the full window.
    monkeypatch.setenv("SHUTDOWN_DRAIN_SECONDS", "0.1")

    store = DedupStore(cfg.dedup_db_path)
    for _ in range(3):
        store.record_attempt("rebar~main~Iabc", "rev2")
    timeline: list[str] = []

    def fake_get_change_event(self, change_id):
        return {
            "type": "manual-rerun",
            "change": {"id": "rebar~main~Iabc", "number": 42, "project": "rebar"},
            "patchSet": {"number": 2, "revision": "rev2", "ref": "refs/changes/42/42/2"},
        }

    monkeypatch.setattr(gcmod.GerritClient, "get_change_event", fake_get_change_event)

    def fake_reset_vote(self, change_id, revision):
        timeline.append("reset_vote")
        return 200

    def fake_has_vote(self, change_id, revision="current"):
        timeline.append("verify_vote")
        return False

    monkeypatch.setattr(gcmod.GerritClient, "reset_llm_review_vote", fake_reset_vote)
    monkeypatch.setattr(gcmod.GerritClient, "has_llm_review_vote", fake_has_vote)

    original_reset_attempts = DedupStore.reset_attempts

    def recording_reset_attempts(self, change_id, revision):
        timeline.append("reset_attempts")
        return original_reset_attempts(self, change_id, revision)

    monkeypatch.setattr(DedupStore, "reset_attempts", recording_reset_attempts)

    with TestClient(appmod.app) as client:
        resp = client.post("/rerun?token=tok&change=42")

    assert resp.status_code == 202
    assert resp.json()["force"] is True
    assert store.attempt_count("rebar~main~Iabc", "rev2") == 0
    assert timeline == ["reset_vote", "verify_vote", "reset_attempts"]


